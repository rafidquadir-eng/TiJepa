"""Write reports/WIPE_MANIFEST.md before the local disk is cleared at project close.

Every path that will be deleted from the instance's local disk is listed with its size and
the location of its durable copy: git (tracked in the repository), the Lambda persistent
filesystem (verified by SHA-256 against the local file, verification files named below), or
a public source it can be re-downloaded from. A path with no durable copy is listed as
BLOCKED and is not deleted.
"""
from __future__ import annotations

import json
import subprocess
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
PFS = "LambdaFilesystem/transfer/proj2"


def size(p: Path) -> int:
    out = subprocess.run(["du", "-sb", str(p)], capture_output=True, text=True).stdout
    return int(out.split()[0]) if out else 0


def human(n: int) -> str:
    for unit in ("B", "KB", "MB", "GB", "TB"):
        if n < 1024 or unit == "TB":
            return f"{n:.1f} {unit}" if unit != "B" else f"{n} B"
        n /= 1024
    return str(n)


def verified(path: str) -> tuple[int, int]:
    """(files verified ok, files) for a verification JSON of (path, status, bytes) rows."""
    rows = json.loads(Path(path).read_text())
    return sum(r[1] == "ok" for r in rows), len(rows)


def main() -> int:
    vdir = Path(sys.argv[1])  # directory holding the verification outputs
    import gzip
    rows_d = json.loads(gzip.open(vdir / "data_verify.json.gz").read())
    data_ok, data_n = sum(r[1] == "ok" for r in rows_d), len(rows_d)
    stage_ok, stage_n = verified(vdir / "stage_verify.json")
    ck = [ln for ln in (vdir / "checkpoint_match.txt").read_text().splitlines() if ln]
    ck_ok = sum(ln.startswith("OK") for ln in ck)
    home = Path.home()
    rows = [
        ("checkpoints/", size(REPO / "checkpoints"),
         f"persistent FS `{PFS}/tijepa_backups/`, `checkpoints/`, `checkpoints_v2/`: "
         f"{ck_ok}/{len(ck)} files matched by SHA-256 (`reports/BACKUP.md`)",
         ck_ok == len(ck)),
        ("data/ (except data/interim/stage/)", size(REPO / "data") - size(REPO / "data/interim/stage"),
         f"persistent FS `{PFS}/data/`: {data_ok}/{data_n} files matched by SHA-256; raw "
         "downloads also re-downloadable from their public sources "
         "(`manifests/datasets.yaml`)", data_ok == data_n),
        ("data/interim/stage/", size(REPO / "data/interim/stage"),
         f"persistent FS `{PFS}/data/interim/stage/`: {stage_ok}/{stage_n} files matched by "
         "SHA-256 (intermediate per-movie clip arrays of the corpus build)",
         stage_ok == stage_n),
        ("logs/", size(REPO / "logs"),
         f"persistent FS `{PFS}/logs_v3/` (copied before deletion); the results they "
         "produced are in git", True),
        ("paper/v3/*/ LaTeX build files (*.aux, *.bbl, *.blg, *.fls, *.fdb_latexmk, "
         "*.log, *.out, build.log)", sum(size(p) for d in ("tmlr", "biorxiv")
                                          for p in (REPO / "paper/v3" / d).glob("*")
                                          if p.suffix in (".aux", ".bbl", ".blg", ".fls",
                                                          ".fdb_latexmk", ".log", ".out")),
         "regenerated by `scripts/84_build_papers_v3.sh`; sources and PDFs are in git", True),
        ("~/.cache/pip", size(home / ".cache/pip"), "package cache; packages re-downloadable "
         "from PyPI (`requirements-lock.txt`)", True),
        ("~/.cache/huggingface", size(home / ".cache/huggingface"),
         "V-JEPA 2 and timm weights; re-downloadable from Hugging Face at the pinned "
         "revisions in `manifests/models.yaml`", True),
        ("~/.cache/torch", size(home / ".cache/torch"), "torch hub cache; re-downloadable",
         True),
    ]
    lines = ["# Wipe manifest (TiJepa close-out)", "",
             "Generated by `scripts/05_wipe_manifest.py` before deleting the instance's local "
             "copies. Nothing listed here is the only copy. Not deleted: the git repository "
             "(`~/proj2` without the paths below), the virtual environment (`~/venv`), and "
             f"everything on the Lambda persistent filesystem (`{PFS}/`).", "",
             "| path (local) | size | durable copy | verified |", "|---|---|---|---|"]
    blocked = []
    for p, n, where, ok in rows:
        lines.append(f"| `{p}` | {human(n)} | {where} | {'yes' if ok else '**BLOCKED**'} |")
        if not ok:
            blocked.append(p)
    lines += ["", f"Total: {human(sum(r[1] for r in rows))}.", "",
              "Git state at the time of writing: every local branch clean and pushed "
              "(`git log origin/<branch>..<branch>` empty for main, tijepa-v0, tijepa-v3)."]
    if blocked:
        lines += ["", "BLOCKED (not deleted): " + ", ".join(blocked)]
    (REPO / "reports" / "WIPE_MANIFEST.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines))
    return 1 if blocked else 0


if __name__ == "__main__":
    raise SystemExit(main())
